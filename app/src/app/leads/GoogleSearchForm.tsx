// l'assistant « Nouveau tableau », et les critères d'un tableau existant, que
// l'on peut redéfinir pour lancer une nouvelle recherche dans le même tableau
// (depuis l'application, ou depuis un lien de partage qui en a le droit).
//
// Les listes sont des listes maison plutôt que `<datalist>` : celle du navigateur
// ne s'ouvre qu'une fois la saisie commencée sur la plupart des navigateurs, et
// pas du tout de façon fiable sur iPhone — le champ semblait simplement ne rien
// proposer.

