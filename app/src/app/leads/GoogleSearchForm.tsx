// ─── Liste déroulante avec saisie ─────────────────────────────────────────────

type ComboGroup = { label?: string; items: string[] };

/**
 * Un champ texte qui ouvre sa liste au premier clic, la filtre à la frappe, et
 * accepte aussi une valeur qui n'y figure pas.
 *
 * Clavier : ↑/↓ pour parcourir, Entrée pour choisir, Échap pour fermer. Les
 * options se choisissent au `mousedown` : le champ garde le focus, et la liste
 * ne se ferme pas avant d'avoir reçu le clic — c'est ce qui la rend utilisable
 * au doigt comme à la souris.
 */
function Combobox({
  label,
  placeholder,
  groups,
  value,
  onChange,
  onPick,
  exclude = [],
  allowCustom = true,
  disabled,
  inputId,
}: {
  label: string;
  placeholder?: string;
  groups: ComboGroup[];
  value: string;
  onChange: (text: string) => void;
  /** Choix d'une option (ou de la saisie libre). */
  onPick: (item: string) => void;
  /** Déjà choisies : n'apparaissent plus. */
  exclude?: string[];
  allowCustom?: boolean;
  disabled?: boolean;
  inputId?: string;
}) {
  const [open, setOpen] = useState(false);
  const [active, setActive] = useState(0);
  const listId = useId();
  const listRef = useRef<HTMLUListElement>(null);

  const norm = (t: string) => t.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();
  const q = norm(value);
  const excluded = new Set(exclude.map(norm));

  const visible = useMemo(() => {
    return groups
      .map(g => ({
        label: g.label,
        items: g.items.filter(i => !excluded.has(norm(i)) && (!q || norm(i).includes(q))),
      }))
      .filter(g => g.items.length > 0);
  }, [groups, q, exclude.join('|')]);

  const flat = visible.flatMap(g => g.items);
  const exact = flat.some(i => norm(i) === q);
  const custom = allowCustom && value.trim() && !exact && !excluded.has(q) ? value.trim() : null;
  const options = custom ? [custom, ...flat] : flat;

  useEffect(() => setActive(0), [q, open]);
  useEffect(() => {
    listRef.current?.querySelector(`[data-index="${active}"]`)?.scrollIntoView({ block: 'nearest' });
  }, [active]);

  function choose(item: string) {
    onPick(item);
    setOpen(false);
  }

  let index = custom ? 1 : 0;
  return (
    <div className='relative'>
      <div className='relative'>
        <input
          id={inputId}
          className='input pr-9'
          role='combobox'
          aria-label={label}
          aria-expanded={open}
          aria-controls={listId}
          aria-autocomplete='list'
          aria-activedescendant={open && options.length ? `${listId}-${active}` : undefined}
          autoComplete='off'
          placeholder={placeholder}
          value={value}
          disabled={disabled}
          onChange={e => { onChange(e.target.value); setOpen(true); }}
          onFocus={() => setOpen(true)}
          onClick={() => setOpen(true)}
          onBlur={() => setOpen(false)}
          onKeyDown={e => {
            if (e.key === 'ArrowDown') { e.preventDefault(); setOpen(true); setActive(a => Math.min(a + 1, options.length - 1)); }
            else if (e.key === 'ArrowUp') { e.preventDefault(); setActive(a => Math.max(a - 1, 0)); }
            else if (e.key === 'Enter') {
              if (open && options[active]) { e.preventDefault(); choose(options[active]); }
              else if (custom) { e.preventDefault(); choose(custom); }
            } else if (e.key === 'Escape' && open) { e.preventDefault(); e.stopPropagation(); setOpen(false); }
          }}
        />
        <button
          type='button'
          tabIndex={-1}
          aria-label={`Afficher la liste — ${label}`}
          className='absolute right-1 top-1/2 flex h-8 w-8 -translate-y-1/2 items-center justify-center rounded-md text-muted hover:text-ink'
          disabled={disabled}
          onMouseDown={e => { e.preventDefault(); setOpen(o => !o); (e.currentTarget.previousElementSibling as HTMLInputElement)?.focus(); }}
        >
          <LuChevronDown size={16} />
        </button>
      </div>
      {open && options.length > 0 && (
        <ul
          ref={listRef}
          id={listId}
          role='listbox'
          aria-label={label}
          className='absolute left-0 right-0 z-30 mt-1 max-h-64 overflow-y-auto overscroll-contain rounded-xl border border-line bg-white py-1 shadow-lg'
        >
          {custom && (
            <li
              id={`${listId}-0`}
              data-index={0}
              role='option'
              aria-selected={active === 0}
              className={`flex cursor-pointer items-center gap-2 px-3 py-2 text-sm ${active === 0 ? 'bg-accent-50 text-ink' : 'text-ink-700'}`}
              onMouseDown={e => { e.preventDefault(); choose(custom); }}
              onMouseEnter={() => setActive(0)}
            >
              <LuPlus size={14} className='shrink-0 text-accent-600' />
              Utiliser « {custom} »
            </li>
          )}
          {visible.map(g => (
            <li key={g.label ?? 'all'} role='presentation'>
              {g.label && (
                <div className='px-3 pb-1 pt-2 text-[11px] font-semibold uppercase tracking-wide text-muted'>{g.label}</div>
              )}
              <ul role='presentation'>
                {g.items.map(item => {
                  const i = index++;
                  return (
                    <li
                      key={item}
                      id={`${listId}-${i}`}
                      data-index={i}
                      role='option'
                      aria-selected={active === i}
                      className={`cursor-pointer px-3 py-2 text-sm ${active === i ? 'bg-accent-50 text-ink' : 'text-ink-700'}`}
                      onMouseDown={e => { e.preventDefault(); choose(item); }}
                      onMouseEnter={() => setActive(i)}
                    >
                      {item}
                    </li>
                  );
                })}
              </ul>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

// ─── Choix en boutons ─────────────────────────────────────────────────────────

function Segmented<T extends string | number>({
  label,
  options,
  value,
  onChange,
  disabled,
}: {
  label: string;
  options: { value: T; label: string; title?: string }[];
  value: T;
  onChange: (v: T) => void;
  disabled?: boolean;
}) {
  return (
    <div>
      <div className='label'>{label}</div>
      <div role='radiogroup' aria-label={label} className='flex flex-wrap gap-1.5'>
        {options.map(o => {
          const on = o.value === value;
          return (
            <button
              key={String(o.value)}
              type='button'
              role='radio'
              aria-checked={on}
              title={o.title}
              disabled={disabled}
              onClick={() => onChange(o.value)}
              className={`h-9 rounded-full border px-3 text-[13px] transition-colors disabled:opacity-60 ${
                on ? 'border-ink bg-ink text-white' : 'border-line bg-white text-ink-700 hover:border-ink/30'
              }`}
            >
              {o.label}
            </button>
          );
        })}
      </div>
    </div>
  );
}

// ─── Les critères ─────────────────────────────────────────────────────────────

/** L'éditeur de critères, sans titre ni bouton : partagé par la création et la modification. */
export function CriteriaFields({
  value,
  onChange,
  disabled,
}: {
  value: GoogleSearchCriteria;
  onChange: (next: GoogleSearchCriteria) => void;
  disabled?: boolean;
}) {
  const [typeText, setTypeText] = useState('');
  const set = <K extends keyof GoogleSearchCriteria>(key: K, v: GoogleSearchCriteria[K]) => onChange({ ...value, [key]: v });
  const full = value.businessTypes.length >= MAX_BUSINESS_TYPES;

  const cityGroups = useMemo<ComboGroup[]>(() => {
    const byProv = PROVINCES.map(p => ({
      label: p.name,
      items: CITY_SUGGESTIONS.filter(c => c.province === p.code).map(c => c.city),
    })).filter(g => g.items.length > 0);
    // La province choisie d'abord : c'est là qu'on cherche presque toujours.
    return [...byProv.filter(g => g.label === PROVINCES.find(p => p.code === value.province)?.name), ...byProv.filter(g => g.label !== PROVINCES.find(p => p.code === value.province)?.name)];
  }, [value.province]);

  return (
    <div className='space-y-5'>
      {/* Quoi */}
      <div>
        <label className='label required'>Type d'entreprise</label>
        {value.businessTypes.length > 0 && (
          <div className='mb-2 flex flex-wrap gap-1.5' aria-label="Types d'entreprise choisis">
            {value.businessTypes.map(t => (
              <span key={t} className='inline-flex items-center gap-1 rounded-full bg-accent-50 py-1 pl-3 pr-1 text-[13px] font-medium text-accent-800'>
                {t}
                {!disabled && (
                  <button
                    type='button'
                    className='flex h-6 w-6 items-center justify-center rounded-full text-accent-700 hover:bg-accent-100'
                    aria-label={`Retirer ${t}`}
                    onClick={() => set('businessTypes', value.businessTypes.filter(x => x !== t))}
                  >
                    <LuX size={13} />
                  </button>
                )}
              </span>
            ))}
          </div>
        )}
        {!full && (
          <Combobox
            label="Type d'entreprise"
            placeholder={value.businessTypes.length ? 'Ajouter un autre type…' : 'Ex : Plombier, Restaurant, Agence web…'}
            groups={BUSINESS_TYPE_GROUPS}
            value={typeText}
            onChange={setTypeText}
            exclude={value.businessTypes}
            disabled={disabled}
            onPick={item => {
              set('businessTypes', [...value.businessTypes, item].slice(0, MAX_BUSINESS_TYPES));
              setTypeText('');
            }}
          />
        )}
        <p className='mt-1 text-xs text-muted'>
          {full
            ? `${MAX_BUSINESS_TYPES} types au plus — chacun est une recherche Google de plus.`
            : `Jusqu'à ${MAX_BUSINESS_TYPES} types, cherchés l'un après l'autre. Soyez précis : « Agence web » plutôt que « agence ».`}
        </p>
      </div>

      {/* Où */}
      <div className='grid grid-cols-1 gap-3 sm:grid-cols-[1fr_12rem]'>
        <div>
          <label className='label required'>Ville</label>
          <Combobox
            label='Ville'
            placeholder='Ex : Montréal, Laval, Québec'
            groups={cityGroups}
            value={value.city}
            onChange={city => set('city', city)}
            disabled={disabled}
            onPick={city => {
              // Choisir une ville connue règle aussi sa province.
              const known = CITY_SUGGESTIONS.find(c => c.city === city);
              onChange({ ...value, city, province: known?.province ?? value.province });
            }}
          />
        </div>
        <div>
          <label className='label' htmlFor='gs-province'>Province</label>
          <select id='gs-province' className='input' value={value.province} onChange={e => set('province', e.target.value)} disabled={disabled}>
            {PROVINCES.map(p => <option key={p.code} value={p.code}>{p.name}</option>)}
          </select>
        </div>
      </div>
      <Segmented
        label='Rayon autour de la ville'
        options={RADIUS_CHOICES.map(r => ({ value: r as number, label: radiusLabel(r) }))}
        value={value.radius}
        onChange={v => set('radius', v)}
        disabled={disabled}
      />

      {/* Filtres */}
      <div className='space-y-4 rounded-xl border border-line p-3.5'>
        <div className='space-y-2'>
          <Segmented
            label='Note Google'
            options={RATING_PRESETS.map(p => ({ value: p.key, label: p.label }))}
            value={ratingPresetKey(value)}
            onChange={key => {
              const p = RATING_PRESETS.find(x => x.key === key)!;
              onChange({ ...value, minRating: p.minRating, maxRating: p.maxRating, includeUnrated: p.maxRating > 0 && value.includeUnrated });
            }}
            disabled={disabled}
          />
          {value.maxRating > 0 && (
            <label className={`flex items-center gap-2.5 text-sm ${disabled ? 'opacity-70' : 'cursor-pointer'}`}>
              <input
                type='checkbox'
                className='h-4 w-4 rounded accent-accent-600'
                checked={value.includeUnrated}
                onChange={e => set('includeUnrated', e.target.checked)}
                disabled={disabled}
              />
              Inclure aussi les entreprises sans aucun avis
            </label>
          )}
        </div>
        <Segmented
          label='Site web'
          options={WEBSITE_CHOICES.map(w => ({ value: w.value, label: w.label, title: w.hint }))}
          value={value.website}
          onChange={v => set('website', v)}
          disabled={disabled}
        />
        <div className='space-y-2'>
          <label className={`flex items-center gap-2.5 text-sm ${disabled ? 'opacity-70' : 'cursor-pointer'}`}>
            <input
              type='checkbox'
              className='h-4 w-4 rounded accent-accent-600'
              checked={value.requirePhone}
              onChange={e => set('requirePhone', e.target.checked)}
              disabled={disabled}
            />
            Téléphone requis
          </label>
          <label className={`flex items-start gap-2.5 text-sm ${disabled ? 'opacity-70' : 'cursor-pointer'}`}>
            <input
              type='checkbox'
              className='mt-0.5 h-4 w-4 rounded accent-accent-600'
              checked={value.skipKnown}
              onChange={e => set('skipKnown', e.target.checked)}
              disabled={disabled}
            />
            <span>
              Ignorer les entreprises déjà prospectées
              <span className='block text-xs text-muted'>
                Sur un autre tableau ou supprimées d'un tableau. Sinon, elles sont ajoutées avec la
                mention « Déjà prospecté » et leur historique.
              </span>
            </span>
          </label>
        </div>
      </div>

      {/* Combien */}
      <div className='grid grid-cols-1 gap-4 sm:grid-cols-2'>
        <Segmented
          label='Nombre de prospects'
          options={RESULT_CHOICES.map(r => ({ value: r as number, label: String(r) }))}
          value={value.maxResults}
          onChange={v => set('maxResults', v)}
          disabled={disabled}
        />
        <Segmented
          label='Langue des fiches'
          options={[{ value: 'fr' as const, label: 'Français' }, { value: 'en' as const, label: 'Anglais' }]}
          value={value.language}
          onChange={v => set('language', v)}
          disabled={disabled}
        />
      </div>
    </div>
  );
}

function googleError(err: any): string {
  const msg = err?.message ?? 'Erreur lors de la recherche';
  return msg.includes('GOOGLE_PLACES_API_KEY')
    ? 'Clé API Google Places manquante. Ajoutez GOOGLE_PLACES_API_KEY dans .env.server.'
    : msg;
}

function SearchingNotice() {
  return (
    <div className='flex items-center gap-3 rounded-xl border border-accent-200 bg-accent-50 p-4 text-sm text-accent-700'>
      <LuLoader size={18} className='shrink-0 animate-spin' />
      <span>Recherche en cours… jusqu'à une minute selon le nombre de prospects et de filtres.</span>
    </div>
  );
}

// ─── New search form ──────────────────────────────────────────────────────────

export function SearchForm({
  onClose,
  onDone,
  initialValues,
}: {
  onClose: () => void;
  onDone: (id: string) => void;
  initialValues?: Partial<SearchFormValues>;
}) {
  const [form, setForm] = useState<SearchFormValues>(() => ({
    ...defaultForm(),
    ...initialValues,
    criteria: normalizeCriteria(initialValues?.criteria ?? defaultCriteria()),
  }));
  const [loading, setLoading] = useState(false);

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    const problem = criteriaProblem(form.criteria);
    if (problem) return toast.error(problem);
    setLoading(true);
    try {
      const result: any = await searchLeads({
        title: form.title.trim() || criteriaTitle(form.criteria),
        description: form.description || undefined,
        // @ts-ignore -- purpose added, Wasp will regen types on restart
        purpose: form.purpose || undefined,
        filters: form.criteria as any,
      });
      toast.success(`${result.leads?.length ?? 0} prospect(s) trouvé(s)`);
      onDone(result.id);
    } catch (err: any) {
      toast.error(googleError(err), { duration: 6000 });
    } finally {
      setLoading(false);
    }
  }

  return (
    <form onSubmit={handleSubmit} className='space-y-5'>
      <p className='text-sm text-muted'>
        Dites ce que vous cherchez et où : Gestia interroge Google Maps et crée une carte par
        entreprise trouvée, avec ses coordonnées.
      </p>

      <div>
        <label className='label' htmlFor='gs-title'>Nom du tableau</label>
        <input
          id='gs-title'
          className='input'
          placeholder={form.criteria.businessTypes.length && form.criteria.city ? criteriaTitle(form.criteria) : 'Ex : Plombiers Montréal — mai 2026'}
          value={form.title}
          onChange={e => setForm(f => ({ ...f, title: e.target.value }))}
        />
      </div>

      <div>
        <label className='label' htmlFor='gs-purpose'>Objectif de la prospection <span className='font-normal text-muted'>(optionnel)</span></label>
        <input
          id='gs-purpose'
          className='input'
          placeholder='Ex : proposer une refonte de site web, offrir un audit SEO gratuit…'
          value={form.purpose}
          onChange={e => setForm(f => ({ ...f, purpose: e.target.value }))}
        />
        <p className='mt-1 text-xs text-muted'>L'IA s'en sert pour rédiger les courriels de ce tableau.</p>
      </div>

      <hr className='border-line' />

      <CriteriaFields value={form.criteria} onChange={criteria => setForm(f => ({ ...f, criteria }))} disabled={loading} />

      {loading && <SearchingNotice />}

      <div className='flex items-center justify-end gap-2 pt-2'>
        <button type='button' className='btn-secondary' onClick={onClose} disabled={loading}>Annuler</button>
        <button type='submit' className='btn-primary gap-2' disabled={loading}>
          {loading ? <LuLoader size={16} className='animate-spin' /> : <LuSearch size={16} />}
          Lancer la prospection
        </button>
      </div>
    </form>
  );
}

// ─── Critères d'un tableau existant ───────────────────────────────────────────

/**
 * Redéfinir les critères d'un tableau Google et relancer une recherche.
 *
 * Les nouveaux critères sont enregistrés sur le tableau, et les entreprises
 * trouvées s'ajoutent en tête de « Nouveau » — jamais celles qu'il contient déjà.
 * Le même écran sert depuis un lien de partage : `useBoardAction` appelle alors
 * l'opération du lien, qui exige le droit « Critères ».
 */
export function BoardCriteriaEditor({
  searchId,
  criteria: saved,
  onClose,
  onSearched,
}: {
  searchId: string;
  criteria: unknown;
  onClose: () => void;
  /** Après une recherche qui a ajouté des prospects. */
  onSearched: () => void;
}) {
  const [criteria, setCriteria] = useState<GoogleSearchCriteria>(() => normalizeCriteria(saved));
  const [loading, setLoading] = useState(false);
  const [empty, setEmpty] = useState<{ radiusKm: number; next: number | null } | null>(null);
  const run = useBoardAction<any, any>(fetchMoreLeads, fetchMoreLeadsByToken);

  async function search(radiusOverride?: number) {
    const problem = criteriaProblem(criteria);
    if (problem) return toast.error(problem);
    setLoading(true);
    setEmpty(null);
    try {
      const res = await run({ searchId, filters: criteria, ...(radiusOverride ? { radiusOverride } : {}) });
      const usedRadius = radiusOverride ?? criteria.radius;
      if (radiusOverride) setCriteria(c => ({ ...c, radius: radiusOverride }));
      if (res.added > 0) {
        toast.success(`${res.added} nouveau${res.added > 1 ? 'x' : ''} prospect${res.added > 1 ? 's' : ''} ajouté${res.added > 1 ? 's' : ''} au tableau`);
        onSearched();
        onClose();
      } else {
        setEmpty({ radiusKm: usedRadius / 1000, next: res.nextExpandedRadiusKm ?? null });
      }
    } catch (err: any) {
      toast.error(googleError(err), { duration: 6000 });
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className='space-y-5'>
      <p className='text-sm text-muted'>
        Modifiez les critères puis lancez une nouvelle recherche : les entreprises trouvées
        s'ajoutent en tête de la première colonne, sans doublon avec celles déjà sur le tableau.
      </p>
      <CriteriaFields value={criteria} onChange={c => { setCriteria(c); setEmpty(null); }} disabled={loading} />

      {loading && <SearchingNotice />}
      {empty && !loading && (
        <div className='rounded-xl border border-amber-200 bg-amber-50 p-3.5 text-sm text-amber-800' role='status'>
          <p className='font-medium'>Aucune nouvelle entreprise dans un rayon de {empty.radiusKm} km.</p>
          <p className='mt-0.5 text-amber-700'>
            {empty.next ? 'Élargissez la zone, ou essayez un autre type d’entreprise.' : 'Essayez un autre type d’entreprise ou une autre ville.'}
          </p>
          {empty.next && (
            <button type='button' className='btn-secondary mt-2.5 h-9 gap-1.5 px-3 text-sm' onClick={() => search(empty.next! * 1000)}>
              <LuMapPin size={14} />
              Élargir à {empty.next} km et chercher
            </button>
          )}
        </div>
      )}

      <div className='flex items-center justify-end gap-2 pt-1'>
        <button type='button' className='btn-secondary' onClick={onClose} disabled={loading}>Fermer</button>
        <button type='button' className='btn-primary gap-2' onClick={() => search()} disabled={loading}>
          {loading ? <LuLoader size={16} className='animate-spin' /> : <LuSearch size={16} />}
          Lancer la recherche
        </button>
      </div>
    </div>
  );
}

