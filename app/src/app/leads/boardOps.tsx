type CardFieldInput = { key: string; label: string; onCard: boolean; onDetail?: boolean };
type TemplateInput = {
  id?: string | null;
  searchId: string;
  channel?: string;
  name: string;
  subject?: string;
  body: string;
  defaultStatus?: string | null;
};

export type BoardOps = {
  /** Vrai dans le portail d'un lien de partage. */
  viaLink: boolean;
  createStatus: (args: { searchId?: string; key: string; label: string; color: string; order: number }) => Promise<any>;
  updateStatus: (args: { id: string; label?: string; color?: string; order?: number }) => Promise<any>;
  deleteStatus: (args: { id: string }) => Promise<any>;
  reorderStatuses: (args: { items: { id: string; order: number }[] }) => Promise<any>;
  overrideStatuses: (args: { searchId: string }) => Promise<any>;
  resetStatuses: (args: { searchId: string }) => Promise<{ orphaned: number }>;
  saveCardFields: (args: { searchId?: string; fields: CardFieldInput[] }) => Promise<any>;
  resetCardFields: (args: { searchId: string }) => Promise<any>;
  /** Les modèles du tableau. */
  useTemplates: (searchId: string) => { data: any[] | undefined; refetch: () => unknown };
  /** Ce que l'aperçu d'un modèle affiche : entreprise, expéditeur, copie. */
  useTemplateContext: () => { company: any; senderInfo: any; copyToCompany: string | null };
  upsertTemplate: (args: TemplateInput) => Promise<any>;
  deleteTemplate: (args: { id: string }) => Promise<any>;
  exportCsv: (args: { searchId: string }) => Promise<{ csv: string }>;
};

const appOps: BoardOps = {
  viaLink: false,
  createStatus: args => createLeadStatusConfig(args as any),
  updateStatus: args => updateLeadStatusConfig(args as any),
  deleteStatus: args => deleteLeadStatusConfig(args),
  reorderStatuses: args => (reorderLeadStatusConfigs as any)(args),
  overrideStatuses: args => (overrideBoardStatuses as any)(args),
  resetStatuses: args => (resetBoardStatuses as any)(args),
  saveCardFields: args => (saveLeadCardFields as any)(args),
  resetCardFields: args => (resetLeadCardFields as any)(args),
  useTemplates: searchId => {
    const { data, refetch } = useQuery(getProspectTemplates as any, { searchId });
    return { data: data as any[] | undefined, refetch };
  },
  useTemplateContext: () => {
    const { data: company } = useQuery(getCurrentCompany);
    const { data: senderInfo } = useQuery(getMailSenderAddress as any);
    const { copyToCompany } = useEmailCapability();
    return { company, senderInfo, copyToCompany };
  },
  upsertTemplate: args => (upsertProspectTemplate as any)(args),
  deleteTemplate: args => (deleteProspectTemplate as any)(args),
  exportCsv: args => exportLeads(args),
};

function linkOps(token: string): BoardOps {
  // Le `searchId` de l'appelant est écarté : le serveur prend celui du lien.
  const strip = <T extends { searchId?: string }>({ searchId: _ignored, ...rest }: T) => ({ ...rest, token });
  return {
    viaLink: true,
    createStatus: args => (createLeadStatusConfigByToken as any)(strip(args)),
    updateStatus: args => (updateLeadStatusConfigByToken as any)({ ...args, token }),
    deleteStatus: args => (deleteLeadStatusConfigByToken as any)({ ...args, token }),
    reorderStatuses: args => (reorderLeadStatusConfigsByToken as any)({ ...args, token }),
    overrideStatuses: () => (overrideBoardStatusesByToken as any)({ token }),
    resetStatuses: () => (resetBoardStatusesByToken as any)({ token }),
    saveCardFields: args => (saveLeadCardFieldsByToken as any)(strip(args)),
    resetCardFields: () => (resetLeadCardFieldsByToken as any)({ token }),
    useTemplates: () => {
      const { data, refetch } = useQuery(getProspectTemplatesByToken as any, { token }, { retry: false } as any);
      return { data: data as any[] | undefined, refetch };
    },
    useTemplateContext: () => {
      const { data } = useQuery(getTemplateContextByToken as any, { token }, { retry: false } as any);
      const ctx = data as any;
      return { company: ctx?.company, senderInfo: ctx?.sender, copyToCompany: ctx?.copyToCompany ?? null };
    },
    upsertTemplate: args => (upsertProspectTemplateByToken as any)(strip(args)),
    deleteTemplate: args => (deleteProspectTemplateByToken as any)({ ...args, token }),
    exportCsv: () => (exportLeadsByToken as any)({ token }),
  };
}

const linkOpsCache = new Map<string, BoardOps>();

export function useBoardOps(): BoardOps {
  const token = useShareToken();
  if (!token) return appOps;
  let ops = linkOpsCache.get(token);
  if (!ops) {
    ops = linkOps(token);
    linkOpsCache.set(token, ops);
  }
  return ops;
}

/**
 * `useQuery` sur l'opération de l'application, ou sur sa jumelle de lien dans
 * le portail. Le `searchId` reste dans les arguments : le serveur l'écarte pour
 * prendre celui du lien.
 */
export function useBoardQuery(appQuery: any, linkQuery: any, args: any, options?: any) {
  const token = useShareToken();
  return useQuery(
    token ? linkQuery : appQuery,
    token ? { ...(args ?? {}), token } : args,
    token ? { retry: false, ...(options ?? {}) } : options,
  );
}

/** L'action de l'application, ou sa jumelle de lien dans le portail. */
export function useBoardAction<A = any, R = any>(appAction: any, linkAction: any): (args: A) => Promise<R> {
  const token = useShareToken();
  return useCallback(
    (args: A) => (token ? linkAction({ ...(args as any), token }) : appAction(args)),
    [token, appAction, linkAction],
  );
}

/** Télécharge le CSV renvoyé par l'export. */
export function downloadCsv(csv: string, title: string) {
  const blob = new Blob(['﻿' + csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(title || 'export').replace(/[^a-z0-9]/gi, '_')}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}
