// Les appels serveur des réglages d'un tableau — statuts, cartes, modèles,
// export — dans l'application ou depuis un lien de partage.
//
// Les écrans de réglage sont les mêmes des deux côtés : ils demandent leurs
// opérations ici plutôt que de les importer. Dans l'application, ce sont les
// opérations authentifiées ; dans le portail, leurs jumelles `…ByToken`, qui
// ignorent le `searchId` reçu et s'en tiennent au tableau du lien.
//
// Le mode est fixé par le fournisseur et ne change pas au cours d'un rendu :
// les crochets `use…` ci-dessous s'appellent donc toujours dans le même ordre.

